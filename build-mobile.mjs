import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.join(projectRoot, "index.html");
const outputPath = path.join(projectRoot, "每日记-手机版.html");
const vendorScriptPattern = /<script src="(vendor\/[^"]+)"><\/script>/g;

let html = readFileSync(sourcePath, "utf8");
const vendorScripts = [...html.matchAll(vendorScriptPattern)].map((match) => match[1]);

if (vendorScripts.length === 0) {
  throw new Error("index.html does not reference any vendor scripts");
}

for (const source of vendorScripts) {
  const filePath = path.resolve(projectRoot, source);
  if (!filePath.startsWith(projectRoot + path.sep)) {
    throw new Error(`Refusing to inline a file outside the project: ${source}`);
  }

  const code = readFileSync(filePath, "utf8");
  if (/<\/script/i.test(code)) {
    throw new Error(`Vendor script contains a closing script tag: ${source}`);
  }

  html = html.replace(
    `<script src="${source}"></script>`,
    `<script data-source="${source}">\n${code}\n</script>`
  );
}

if (/<script src="vendor\//.test(html)) {
  throw new Error("The generated mobile file still references vendor scripts");
}

const banner = "<!-- Generated by build-mobile.mjs. Edit index.html and rebuild instead. -->\n";
writeFileSync(outputPath, banner + html, "utf8");

console.log(`Generated ${path.basename(outputPath)} with ${vendorScripts.length} local libraries.`);
